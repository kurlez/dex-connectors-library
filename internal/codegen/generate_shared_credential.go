// SharedCredentialTestOutputFile is the generated test of a connector whose host keeps credentials. It checks that a
// shared credential without the host-kept fields decodes, and that only the generated codec and the credential
// refresh driver read those fields.
const SharedCredentialTestOutputFile = "zz_generated_shared_credential_test.go"

// GenerateSharedCredentialTest returns the shared credential test of a manifest whose host keeps credentials.
// connectorImportPath is the Go import path of the connector package, which is also its module path.
func GenerateSharedCredentialTest(manifest schema.Manifest, connectorImportPath string) ([]byte, error) {
	if !HasHostKeptCredentials(manifest) {
		return nil, fmt.Errorf("manifest %s declares no host-kept credentials", manifest.Metadata.Name)
	}
	connector := manifest.Spec.Codegen.Go.Package
	generation := &generator{}
	generation.mustWrite("// Code generated by connectorctl generate; DO NOT EDIT.\n")
	generation.mustWrite("// Copyright (c) 2026 Super Durable\n// SPDX-License-Identifier: MIT\n\n")
	generation.mustWrite("package %s_test\n\n", connector)
	generation.mustWrite("import (\n")
	for _, standardImport := range []string{"encoding/json", "fmt", "go/ast", "go/importer", "go/parser", "go/token", "go/types", "io", "os", "os/exec", "path/filepath", "runtime/debug", "slices", "strings", "testing"} {
		generation.mustWrite("\t%q\n", standardImport)
	}
	generation.mustWrite("\n\t\"github.com/stretchr/testify/require\"\n\t%q\n)\n", connectorImportPath)
	generation.mustWrite("%s\n", strings.ReplaceAll(sharedCredentialHarness, "CONNECTOR", connector))
	generation.mustWrite("// sharedCredentialModulePath is the connector's module, whose root package declares Credentials.\n")
	generation.mustWrite("const sharedCredentialModulePath = %q\n\n", connectorImportPath)
	generation.mustWrite("// hostKeptCredentialFields are the Credentials fields that a host keeps in some authentication method.\n")
	generation.mustWrite("var hostKeptCredentialFields = %s\n\n", goStringSlice(hostKeptCredentialGoNames(manifest)))
	generation.mustWrite("func sharedCredentialMethods() []sharedCredentialMethod {\n\treturn []sharedCredentialMethod{\n")
	for _, method := range manifest.Spec.Auth.AuthMethods() {
		if err := writeSharedCredentialMethod(generation, manifest, method); err != nil {
			return nil, err
		}
	}
	generation.mustWrite("\t}\n}\n\n")
	writeSharedCredentialValues(generation, manifest)
	formatted, err := format.Source(generation.output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated shared credential test: %w", err)
	}
	return formatted, nil
}

func writeSharedCredentialMethod(generation *generator, manifest schema.Manifest, method schema.AuthMethod) error {
	credential := map[string]any{}
	decoded := map[string]string{}
	if selection := credentialSelection(manifest.Spec.Auth); selection != nil {
		credential[selection.wireName], decoded[selection.wireName] = method.ID, method.ID
	}
	var required []string
	isHostKeptRequired := false
	hostKept := schema.HostKeptCredentials(method)
	for _, field := range method.Fields {
		value, rendered, err := sharedCredentialSample(field)
		if err != nil {
			return err
		}
		credential[field.Name], decoded[field.Name] = value, rendered
		isHostKept := slices.Contains(hostKept, field.Name)
		// The rule is restated here, not taken from validateSharedCredential's generator, so that a test checks it.
		if (field.Required && !isHostKept) || slices.Contains(mintedAccessTokenCredentials(method), field.Name) {
			required = append(required, field.Name)
		}
		isHostKeptRequired = isHostKeptRequired || (field.Required && isHostKept)
	}
	encoded, err := json.Marshal(credential)
	if err != nil {
		return fmt.Errorf("encode the sample credential of method %q: %w", method.ID, err)
	}
	name := method.ID
	if name == "" {
		name = "spec.auth"
	}
	generation.mustWrite("\t\t{\n\t\t\tname: %q,\n", name)
	generation.mustWrite("\t\t\tcredential: `%s`,\n", encoded)
	generation.mustWrite("\t\t\tdecoded: %s,\n", goStringMap(decoded))
	generation.mustWrite("\t\t\thostKept: %s,\n", goStringSlice(hostKept))
	generation.mustWrite("\t\t\trequired: %s,\n", goStringSlice(required))
	generation.mustWrite("\t\t\tisHostKeptRequired: %t,\n\t\t},\n", isHostKeptRequired)
	return nil
}

// sharedCredentialSample returns a sample JSON value for field and how sharedCredentialValues renders it decoded.
func sharedCredentialSample(field schema.Field) (any, string, error) {
	sample := "manifest-" + field.Name
	switch field.Type {
	case "string", "secretString":
		return sample, sample, nil
	case "url":
		return "https://manifest.example.com/" + field.Name, "https://manifest.example.com/" + field.Name, nil
	case "enum":
		return field.Enum[0], field.Enum[0], nil
	case "integer":
		return 7, "7", nil
	case "boolean":
		return true, "true", nil
	case "duration":
		return int64(7 * time.Second), (7 * time.Second).String(), nil
	case "stringList":
		return []string{sample}, "[" + sample + "]", nil
	case "stringMap":
		return map[string]string{"key": sample}, "map[key:" + sample + "]", nil
	default:
		return nil, "", fmt.Errorf("credential field %s type %s has no shared credential sample", field.Name, field.Type)
	}
}

// writeSharedCredentialValues writes sharedCredentialValues, which renders every set field by its credential name.
func writeSharedCredentialValues(generation *generator, manifest schema.Manifest) {
	generation.mustWrite("func sharedCredentialValues(credentials %s.Credentials) map[string]string {\n", manifest.Spec.Codegen.Go.Package)
	generation.mustWrite("\tvalues := map[string]string{}\n")
	if selection := credentialSelection(manifest.Spec.Auth); selection != nil {
		generation.mustWrite("\tif credentials.%s != \"\" { values[%q] = credentials.%s }\n", selection.goName, selection.wireName, selection.goName)
	}
	for _, field := range manifest.Spec.Auth.Fields {
		value := "credentials." + field.GoName
		switch field.Type {
		case "secretString":
			generation.mustWrite("\tif %s.Reveal() != \"\" { values[%q] = %s.Reveal() }\n", value, field.Name, value)
		case "enum":
			generation.mustWrite("\tif %s != \"\" { values[%q] = string(%s) }\n", value, field.Name, value)
		case "integer", "duration":
			generation.mustWrite("\tif %s != 0 { values[%q] = fmt.Sprint(%s) }\n", value, field.Name, value)
		case "boolean":
			generation.mustWrite("\tif %s { values[%q] = fmt.Sprint(%s) }\n", value, field.Name, value)
		case "stringList", "stringMap":
			generation.mustWrite("\tif len(%s) > 0 { values[%q] = fmt.Sprint(%s) }\n", value, field.Name, value)
		default:
			generation.mustWrite("\tif %s != \"\" { values[%q] = %s }\n", value, field.Name, value)
		}
	}
	generation.mustWrite("\treturn values\n}\n")
}

// hostKeptCredentialGoNames are the Go names of the fields that some method keeps on the host, in field order.
func hostKeptCredentialGoNames(manifest schema.Manifest) []string {
	var hostKept []string
	for _, method := range manifest.Spec.Auth.AuthMethods() {
		hostKept = append(hostKept, schema.HostKeptCredentials(method)...)
	}
	var goNames []string
	for _, field := range manifest.Spec.Auth.Fields {
		if slices.Contains(hostKept, field.Name) {
			goNames = append(goNames, field.GoName)
		}
	}
	return goNames
}
